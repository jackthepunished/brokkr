//! `brokk` — the Brokkr command-line interface.
//!
//! Phase 1: `version`, stub `init`, and `run --command "..."` for the
//! end-to-end happy path.

use std::path::PathBuf;

use anyhow::{anyhow, Context, Result};
use brokkr_sdk::{run_command, BrokkrClient, TlsConfig};
use clap::{Parser, Subcommand};

/// Top-level CLI entrypoint.
#[derive(Debug, Parser)]
#[command(
    name = "brokk",
    version,
    about = "Brokkr — distributed build & compute grid",
    long_about = None,
    arg_required_else_help = true,
)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

#[derive(Debug, Subcommand)]
enum Command {
    /// Print the brokk version, target triple, and embedded git revision.
    Version,
    /// Initialize a Brokkr project in the current directory.
    Init {
        /// Overwrite existing config files.
        #[arg(long)]
        force: bool,
    },
    /// Run a shell command on the cluster.
    Run {
        /// Control plane endpoint (e.g. `http://127.0.0.1:7878`).
        ///
        /// **Repeatable** (Phase 5 I9b): name every control-plane node of an HA
        /// cluster and `brokk` uses the first one that answers. Any node is a
        /// valid entry point — a follower serves reads and CAS, and redirects
        /// metadata writes to the leader.
        #[arg(long, default_value = "http://127.0.0.1:7878")]
        control: Vec<String>,

        /// Skip the action cache lookup and force re-execution.
        #[arg(long)]
        no_cache: bool,

        /// CA certificate for verifying the control plane server certificate.
        #[arg(long)]
        tls_ca: Option<String>,

        /// Client certificate for mTLS authentication (requires --tls-client-key).
        #[arg(long, requires = "tls_client_key")]
        tls_client_cert: Option<String>,

        /// Client private key for mTLS authentication (requires --tls-client-cert).
        #[arg(long, requires = "tls_client_cert")]
        tls_client_key: Option<String>,

        /// JWT bearer token sent in `authorization: Bearer <token>` on
        /// every outbound RPC. Required when the control plane has
        /// `--auth-jwt-*` enabled (ADR 0011, issue #139). Mutually
        /// exclusive with `--bearer-token-file`.
        #[arg(long, conflicts_with = "bearer_token_file")]
        bearer_token: Option<String>,

        /// Path to a file containing the JWT bearer token. Preferred
        /// for tokens read from disk so they don't appear in `ps` or
        /// `/proc/<pid>/cmdline`. Mutually exclusive with
        /// `--bearer-token`. The file should contain the raw token
        /// bytes; trailing whitespace is trimmed.
        #[arg(long, conflicts_with = "bearer_token")]
        bearer_token_file: Option<PathBuf>,

        /// The command to run, including arguments. Pass via repeated
        /// positional args: `brokk run -- echo hello world`.
        #[arg(trailing_var_arg = true, required = true)]
        argv: Vec<String>,
    },
}

fn main() -> Result<()> {
    tracing_subscriber::fmt()
        .with_env_filter(
            tracing_subscriber::EnvFilter::try_from_default_env()
                .unwrap_or_else(|_| tracing_subscriber::EnvFilter::new("info")),
        )
        .init();

    let cli = Cli::parse();
    match cli.command {
        Command::Version => print_version(),
        Command::Init { force } => init_project(force),
        Command::Run {
            control,
            no_cache,
            tls_ca,
            tls_client_cert,
            tls_client_key,
            bearer_token,
            bearer_token_file,
            argv,
        } => run_subcmd(RunOptions {
            control,
            no_cache,
            tls: TlsOptions {
                ca: tls_ca,
                client_cert: tls_client_cert,
                client_key: tls_client_key,
            },
            bearer: BearerOptions {
                token: bearer_token,
                token_file: bearer_token_file,
            },
            argv,
        }),
    }
}

fn print_version() -> Result<()> {
    println!(
        "brokk {} ({})\nrustc: {}\ntarget: {}",
        env!("CARGO_PKG_VERSION"),
        option_env!("BROKKR_GIT_SHA").unwrap_or("unknown"),
        env!("BROKKR_RUSTC_VERSION"),
        env!("BROKKR_TARGET_TRIPLE"),
    );
    Ok(())
}

