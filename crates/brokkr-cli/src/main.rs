/// Write a scaffolding file to `path`, failing if it already exists
/// unless `force` is true.
fn scaffold_file(path: &std::path::Path, content: &str, force: bool) -> Result<()> {
    if path.exists() && !force {
        return Err(anyhow!(
            "{} already exists; pass --force to overwrite",
            path.display()
        ));
    }
    std::fs::write(path, content).with_context(|| format!("writing {}", path.display()))?;
    println!("  created {}", path.display());
    Ok(())
}

/// Scaffold brokk configuration files in the current directory.
pub fn init_project(force: bool) -> Result<()> {
    let cwd = std::env::current_dir().context("getting current directory")?;
    println!("brokk init: scaffolding in {}", cwd.display());

    scaffold_file(&cwd.join("brokk.toml"), BROKK_TOML_CONTENT, force)?;
    scaffold_file(&cwd.join(".brokkrignore"), BROKKIGNORE_CONTENT, force)?;

    let workflow_dir = cwd.join(".github").join("workflows");
    std::fs::create_dir_all(&workflow_dir)
        .with_context(|| format!("creating {}", workflow_dir.display()))?;
    scaffold_file(&workflow_dir.join("brokkr.yml"), WORKFLOW_YAML, force)?;

    println!("brokk init: done");
    Ok(())
}

/// TLS-related CLI options for `brokk run`. Bundled to keep the
/// `run_subcmd` signature below clippy's `too_many_arguments` threshold.
#[derive(Debug, Default)]
struct TlsOptions {
    ca: Option<String>,
    client_cert: Option<String>,
    client_key: Option<String>,
}

/// Bearer-token CLI options for `brokk run`. Mutually exclusive at the
/// clap layer (`conflicts_with`); we materialise one of three states
/// (`Token`, `TokenFile`, `None`) into the resolved token in
/// `run_subcmd`.
#[derive(Debug, Default)]
struct BearerOptions {
    token: Option<String>,
    token_file: Option<PathBuf>,
}

/// Everything `run_subcmd` needs from the CLI layer. Bundled for the
/// same reason as [`TlsOptions`] and [`BearerOptions`].
struct RunOptions {
    control: Vec<String>,
    no_cache: bool,
    tls: TlsOptions,
    bearer: BearerOptions,
    argv: Vec<String>,
}

fn run_subcmd(opts: RunOptions) -> Result<()> {
    if opts.argv.is_empty() {
        return Err(anyhow!("`brokk run` requires a command"));
    }

    // Runtime validation: partial mTLS identity is an error.
    let has_cert = opts.tls.client_cert.is_some();
    let has_key = opts.tls.client_key.is_some();
    if has_cert != has_key {
        anyhow::bail!("both --tls-client-cert and --tls-client-key must be provided together");
    }
    if (has_cert || has_key) && opts.tls.ca.is_none() {
        anyhow::bail!("--tls-client-cert and --tls-client-key require --tls-ca to be provided");
    }

    // Resolve bearer token: `--bearer-token` wins if both are somehow set,
    // but `conflicts_with` on the clap args should already prevent that.
    let bearer = match (opts.bearer.token, opts.bearer.token_file) {
        (Some(t), _) => Some(t),
        (None, Some(path)) => Some(
            std::fs::read_to_string(&path)
                .with_context(|| format!("reading bearer token from {}", path.display()))?
                .trim()
                .to_string(),
        ),
        (None, None) => None,
    };

    let tls = opts.tls.ca.map(|ca| TlsConfig {
        ca_cert: std::path::PathBuf::from(ca),
        client_cert: opts.tls.client_cert.map(std::path::PathBuf::from),
        client_key: opts.tls.client_key.map(std::path::PathBuf::from),
    });

    let control = opts.control;
    let argv = opts.argv;
    let no_cache = opts.no_cache;

    let rt = tokio::runtime::Runtime::new().context("starting tokio runtime")?;
    rt.block_on(async move {
        // Connect with the right combination: TLS, bearer, or both.
        // The `(tls, bearer)` matrix is exhaustive: 0..=1 of each may be
        // set; we materialise it into four branches to keep the call
        // sites readable. The control plane refuses to start in any
        // combination that would silently mis-configure auth (issue
        // #139), so a wrong client-side combo just surfaces as a
        // runtime `UNAUTHENTICATED` here.
        let mut client = connect_first(&control, tls, bearer).await?;
        let outcome = run_command(&mut client, &argv, no_cache).await?;
        // Forward stdout/stderr verbatim to the user's terminal.
        use std::io::Write as _;
        std::io::stdout().write_all(&outcome.stdout)?;
        std::io::stderr().write_all(&outcome.stderr)?;
        eprintln!(
            "[brokk] exit={} cache_hit={}",
            outcome.exit_code, outcome.cache_hit
        );
        std::process::exit(outcome.exit_code);
    })
}

/// Connect to the first control-plane endpoint that answers (Phase 5 I9b W3).
///
/// Endpoints are tried in order with whichever auth combination was
/// configured. Any node of an HA cluster is a valid entry point, so this only
/// needs *a* live node rather than the leader — the leader-redirect metadata
/// (`x-brokkr-leader-addr`, see `brokkr_sdk::redirect`) handles the cases that
/// must reach the leader specifically.
///
/// The last transport error is returned when nothing answers, because "all
/// three refused the connection" and "the third one's certificate is wrong"
/// need different fixes and a synthetic aggregate error hides which it was.
async fn connect_first(
    endpoints: &[String],
    tls: Option<TlsConfig>,
    bearer: Option<String>,
) -> Result<BrokkrClient> {
    if endpoints.is_empty() {
        anyhow::bail!("--control must be given at least once");
    }
    let mut last_error = None;
    for endpoint in endpoints {
        // The `(tls, bearer)` matrix is exhaustive: 0..=1 of each may be set.
        // The control plane refuses to start in any combination that would
        // silently mis-configure auth (issue #139), so a wrong client-side
        // combo surfaces as a runtime `UNAUTHENTICATED` rather than silence.
        let attempt = match (tls.clone(), bearer.clone()) {
            (Some(tls_cfg), Some(token)) => {
                BrokkrClient::connect_with_tls_and_bearer(endpoint.clone(), tls_cfg, token).await
            }
            (Some(tls_cfg), None) => {
                BrokkrClient::connect_with_tls(endpoint.clone(), tls_cfg).await
            }
            (None, Some(token)) => BrokkrClient::connect_with_bearer(endpoint.clone(), token).await,
            (None, None) => BrokkrClient::connect(endpoint.clone()).await,
        };
        match attempt {
            Ok(client) => return Ok(client),
            Err(e) => {
                if endpoints.len() > 1 {
                    eprintln!("[brokk] {endpoint} unreachable ({e}); trying the next endpoint");
                }
                last_error = Some(e);
            }
        }
    }
    Err(last_error
        .map(anyhow::Error::from)
        .unwrap_or_else(|| anyhow!("no control-plane endpoints configured")))
}
